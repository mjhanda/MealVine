/**
 * Regenerates src/data/nutrition/nutritionData.ts from USDA FoodData Central (SR Legacy).
 *
 *   1. Download https://fdc.nal.usda.gov/fdc-datasets/FoodData_Central_sr_legacy_food_csv_2018-04.zip
 *      (sha256 b80817294b8850530aaedf2e515c02593b1824f763a0ff356e5c2081643e6fd0) and unzip it.
 *   2. USDA_DIR=/path/to/FoodData_Central_sr_legacy_food_csv_2018-04 npm run nutrition:build
 *
 * The raw CSVs (~54 MB) are not committed; only the per-ingredient extract is.
 */
import { createReadStream, readFileSync, writeFileSync } from 'node:fs';
import { join } from 'node:path';
import { createInterface } from 'node:readline';
import { INGREDIENTS } from '../src/data/ingredients';
import { ESTIMATES, USDA_MAP } from '../src/data/nutrition/usdaMap';

const DIR = process.env.USDA_DIR;
if (!DIR) throw new Error('Set USDA_DIR to the unzipped SR Legacy CSV folder');

const NUTRIENTS = { 1008: 'kcal', 1003: 'protein', 1004: 'fat', 1258: 'satFat', 1005: 'carbs', 1079: 'fiber', 2000: 'sugar', 1093: 'sodium' } as const;
type Key = (typeof NUTRIENTS)[keyof typeof NUTRIENTS];
const KEYS = Object.values(NUTRIENTS) as Key[];

const parseCsv = (line: string) =>
  line.match(/("([^"]|"")*"|[^,]*)(,|$)/g)!.map((c) => c.replace(/,$/, '').replace(/^"|"$/g, '').replace(/""/g, '"'));

async function main() {
  const missingMap = Object.keys(INGREDIENTS).filter((id) => !USDA_MAP[id]);
  if (missingMap.length) throw new Error(`No USDA mapping for: ${missingMap.join(', ')}`);

  const wanted = new Set(Object.values(USDA_MAP).flatMap((m) => m.parts.map((p) => String(p.fdcId))).filter((id) => id !== '0'));
  const descriptions = new Map<string, string>();
  readFileSync(join(DIR!, 'food.csv'), 'utf8').split('\n').slice(1).filter(Boolean).forEach((line) => {
    const [id, , description] = parseCsv(line);
    if (wanted.has(id)) descriptions.set(id, description);
  });
  const notFound = [...wanted].filter((id) => !descriptions.has(id));
  if (notFound.length) throw new Error(`fdc ids not in SR Legacy: ${notFound.join(', ')}`);

  // food_nutrient.csv is ~36 MB, so stream it.
  const per100 = new Map<string, Partial<Record<Key, number>>>();
  const rl = createInterface({ input: createReadStream(join(DIR!, 'food_nutrient.csv')) });
  for await (const line of rl) {
    const [, fdcId, nutrientId, amount] = parseCsv(line);
    const key = NUTRIENTS[Number(nutrientId) as keyof typeof NUTRIENTS];
    if (!key || !wanted.has(fdcId)) continue;
    const row = per100.get(fdcId) ?? {};
    row[key] = Number(amount);
    per100.set(fdcId, row);
  }

  const round = (n: number) => Math.round(n * 100) / 100;
  const nutrients: Record<string, Record<Key, number>> = {};
  const sources: Record<string, unknown> = {};
  for (const [id, m] of Object.entries(USDA_MAP).sort(([a], [b]) => a.localeCompare(b))) {
    const missing = new Set<Key>();
    let values: Record<Key, number>;
    if (m.basis === 'estimate') {
      values = ESTIMATES[id];
      if (!values) throw new Error(`estimate mapping without ESTIMATES entry: ${id}`);
    } else {
      values = Object.fromEntries(KEYS.map((k) => [k, 0])) as Record<Key, number>;
      for (const part of m.parts) {
        if (part.fdcId === 0) continue; // water
        const row = per100.get(String(part.fdcId)) ?? {};
        for (const k of KEYS) {
          if (row[k] === undefined) missing.add(k);
          values[k] += (row[k] ?? 0) * part.weight;
        }
      }
    }
    nutrients[id] = Object.fromEntries(KEYS.map((k) => [k, round(values[k])])) as Record<Key, number>;
    sources[id] = {
      basis: m.basis,
      ...(m.note ? { note: m.note } : {}),
      ...(m.refuse ? { refuse: m.refuse } : {}),
      foods: m.parts.filter((p) => p.fdcId !== 0).map((p) => ({ fdcId: p.fdcId, description: descriptions.get(String(p.fdcId)), weight: p.weight })),
      ...(missing.size ? { missing: [...missing] } : {}),
    };
  }

  const out = `// GENERATED by scripts/build-nutrition.ts — do not edit by hand. Edit usdaMap.ts and rebuild.
// Source: USDA FoodData Central, SR Legacy (April 2018). Public domain.
import { IngredientSource, NutrientValues } from './types';

export const USDA_DATASET = {
  name: 'USDA FoodData Central — SR Legacy',
  release: '2018-04',
  url: 'https://fdc.nal.usda.gov/',
  citation: 'U.S. Department of Agriculture, Agricultural Research Service. FoodData Central: SR Legacy, 2018.',
} as const;

// Per 100 g of the food as purchased/described. kcal, grams, and sodium in mg.
export const NUTRIENTS_PER_100G: Record<string, NutrientValues> = ${JSON.stringify(nutrients, null, 2)};

export const INGREDIENT_SOURCES: Record<string, IngredientSource> = ${JSON.stringify(sources, null, 2)};
`;
  writeFileSync(join(__dirname, '../src/data/nutrition/nutritionData.ts'), out);
  console.log(`wrote ${Object.keys(nutrients).length} ingredients from ${wanted.size} USDA foods`);
}

main();
